import { useAuthStore } from './store/authStore';

export type Lang = 'zh' | 'en';

export type LangText = { zh: string; en: string };

export function useLang(): Lang {
  return useAuthStore((s) => s.lang);
}

export function t(text: LangText, lang: Lang): string {
  return text[lang];
}

export function useT(): (text: LangText) => string {
  const lang = useLang();
  return (text: LangText) => text[lang];
}

